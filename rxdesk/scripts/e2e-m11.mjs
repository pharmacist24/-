// Dose dropdowns: amount / frequency / eye, editable lists in Settings.
export default async function ({ page, shot, check, sleep }) {
  const newRx = async (q) => {
    await page.click('[data-nav="rx"]')
    await page.waitForSelector('#patient-picker')
    await page.fill('#patient-picker', q)
    await sleep(400)
    await page.keyboard.press('Enter')
    await page.waitForSelector('#rx-patient-name')
  }
  const choose = async (row, field, text) => {
    await page.click(`[data-row="${row}"][data-field="${field}"]`)
    await sleep(200)
    await page.locator('.mantine-Autocomplete-option:visible', { hasText: text }).first().click()
    await sleep(150)
  }

  await newRx('فاطمة')
  const fields = await page.locator('[data-row="0"]').evaluateAll((els) => els.map((e) => e.getAttribute('data-field')))
  check(JSON.stringify(fields) === JSON.stringify(['drugName', 'dose', 'frequency']), 'row = drug + amount + frequency only (' + fields.join(',') + ')')
  check((await page.locator('[data-row="0"][data-field="strength"], [data-row="0"][data-field="route"]').count()) === 0, 'no strength / route boxes')

  await page.click('[data-row="0"][data-field="drugName"]')
  await page.keyboard.type('Tobradex', { delay: 20 })
  await page.keyboard.press('Escape')
  await page.click('[data-row="0"][data-field="dose"]')
  await sleep(250)
  const amountOptions = await page.locator('.mantine-Autocomplete-option:visible').allTextContents()
  check(amountOptions.includes('قطرة واحدة') && amountOptions.includes('قطرتين'), 'amount dropdown opens with the full list: ' + amountOptions.slice(0, 4).join(' | '))
  await page.locator('.mantine-Autocomplete-option:visible', { hasText: 'قطرتين' }).first().click()
  await choose(0, 'frequency', '4 مرات يومياً')
  check((await page.inputValue('[data-row="0"][data-field="dose"]')) === 'قطرتين', 'amount chosen from dropdown')
  check((await page.inputValue('[data-row="0"][data-field="frequency"]')) === '4 مرات يومياً', 'frequency chosen from dropdown')

  // typed value not in the list
  await page.click('[data-row="1"][data-field="drugName"]')
  await page.keyboard.type('Artificial tears', { delay: 10 })
  await page.keyboard.press('Escape')
  await page.fill('[data-row="1"][data-field="dose"]', '3 نقط')
  check((await page.inputValue('[data-row="1"][data-field="dose"]')) === '3 نقط', 'a value that is not in the list can be typed')
  check((await page.locator('[data-row="0"][data-field="site"]').count()) === 0, 'eye dropdown hidden until switched on in Settings')
  await shot('90-dropdowns')
  await page.keyboard.press('Control+s')
  await sleep(600)

  // Settings: switch on the eye, add a frequency choice
  await page.click('[data-nav="settings"]')
  await page.click('[data-tab="rxform"]')
  await sleep(300)
  await page.locator('[data-part-toggle="eye"]').dispatchEvent('click')
  await sleep(300)
  await page.locator('[data-list="frequency"] input:not([type=hidden])').first().fill('كل 3 ساعات')
  await page.keyboard.press('Enter')
  await sleep(300)
  await shot('91-settings-dose')

  await newRx('أحمد')
  const fields2 = await page.locator('[data-row="0"]').evaluateAll((els) => els.map((e) => e.getAttribute('data-field')))
  check(fields2.includes('site'), 'eye dropdown appears after enabling it')
  await page.click('[data-row="0"][data-field="drugName"]')
  await page.keyboard.type('Tobradex', { delay: 20 })
  await page.keyboard.press('Escape')
  await choose(0, 'dose', 'قطرة واحدة')
  await page.click('[data-row="0"][data-field="frequency"]')
  await sleep(250)
  const freqOpts = await page.locator('.mantine-Autocomplete-option:visible').allTextContents()
  check(freqOpts.includes('كل 3 ساعات') && !freqOpts.includes('قطرتين'), 'new frequency choice from Settings appears in the frequency dropdown')
  await page.locator('.mantine-Autocomplete-option:visible', { hasText: 'كل 3 ساعات' }).first().click()
  await choose(0, 'site', 'العين اليمنى')
  await page.click('[data-row="1"][data-field="drugName"]')
  await page.keyboard.type('Vigamox', { delay: 20 })
  await page.keyboard.press('Escape')
  await choose(1, 'dose', 'قطرة واحدة')
  await choose(1, 'frequency', '4 مرات يومياً')
  await choose(1, 'site', 'العينين')
  await shot('92-eye-rx')
  await page.keyboard.press('Control+s')
  await sleep(700)
  await page.click('#rx-preview')
  await page.waitForSelector('#preview-frame')
  await sleep(1200)
  const text = await page.frameLocator('#preview-frame').locator('.rx-el-medicines').textContent()
  check(text.includes('قطرة واحدة — كل 3 ساعات — العين اليمنى') && text.includes('العينين'), 'printout shows amount — frequency — eye')
  await shot('93-eye-preview')
  await page.keyboard.press('Escape')

  // Eye clinic preset
  await page.click('[data-nav="settings"]')
  await page.click('[data-tab="rxform"]')
  await page.click('[data-preset="simple"]')
  await sleep(200)
  await page.click('[data-preset="eye"]')
  await sleep(300)
  const pv = await page.locator('#rxform-preview [data-row="0"]').evaluateAll((els) => els.map((e) => e.getAttribute('data-field')))
  check(JSON.stringify(pv) === JSON.stringify(['drugName', 'dose', 'frequency', 'site']), '"Eye clinic" preset: drug + amount + frequency + eye')
  check((await page.locator('[data-list="frequency"]').textContent()).includes('كل 3 ساعات'), 'presets keep the doctor’s own list choices')
}
