// Simple prescription screen (default) and Settings → Prescription screen.
export default async function ({ page, shot, check, sleep }) {
  await page.click('[data-nav="rx"]')
  await page.waitForSelector('#patient-picker')
  await page.fill('#patient-picker', 'أحمد')
  await sleep(400)
  await page.keyboard.press('Enter')
  await page.waitForSelector('#rx-patient-name')

  const fieldsInRow0 = await page.locator('[data-row="0"]').evaluateAll((els) => els.map((e) => e.getAttribute('data-field')))
  check(JSON.stringify(fieldsInRow0) === JSON.stringify(['drugName', 'dose']), 'simple mode: each medicine has only drug + dose boxes (' + fieldsInRow0.join(',') + ')')
  check((await page.locator('#rx-diagnosis').count()) === 1, 'diagnosis shown by default (with treatment suggestions)')
  check((await page.locator('#rx-labs').count()) === 0 && (await page.locator('#rx-next').count()) === 0, 'lab tests and next visit hidden by default')
  check((await page.locator('#rx-notes').count()) === 1, 'advice box shown')
  check((await page.locator('[data-phrase]').count()) === 0, 'side panel hidden by default')

  await page.click('[data-row="0"][data-field="drugName"]')
  await page.keyboard.type('Augm', { delay: 40 })
  await sleep(500)
  await page.keyboard.press('Enter')
  await sleep(300)
  const dose = await page.inputValue('[data-row="0"][data-field="dose"]')
  check(dose === '1 tablet · every 12 hours · 7 days · بعد الأكل', 'picking a drug writes the full dose line: ' + dose)
  check((await page.locator('[data-med-row="0"]').textContent()).includes('1 g · Tab'), 'strength/form shown under the drug name')
  check((await page.locator('[data-allergy-warning]').count()) === 1, 'allergy warning still shown (penicillin)')
  check(await page.evaluate(() => document.activeElement?.getAttribute('data-field') === 'dose'), 'focus jumps to the dose line')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Enter')
  await sleep(150)
  check(await page.evaluate(() => document.activeElement?.getAttribute('data-row') === '1'), 'Enter on the dose line goes to the next medicine')

  // Templates menu in the header
  await page.click('[data-menu="templates"]')
  await page.click('[data-template="Common cold / Flu"]')
  await sleep(300)
  check((await page.locator('[data-med-row]').count()) === 4, 'templates menu inserts medicines')
  await page.fill('#rx-notes', 'راحة وسوائل دافئة')
  await shot('60-simple-rx')
  await page.keyboard.press('Control+s')
  await sleep(700)
  check(/\d/.test(await page.textContent('h3')), 'Ctrl+S saves')

  await page.click('#rx-preview')
  await page.waitForSelector('#preview-frame')
  await sleep(1200)
  const fr = page.frameLocator('#preview-frame')
  check((await fr.locator('text=every 12 hours').count()) === 1, 'printout shows the dose line')
  await shot('61-simple-preview')
  await page.keyboard.press('Escape')

  // Settings: turn on fields and sections
  await page.click('[data-nav="settings"]')
  await page.click('[data-tab="rxform"]')
  await sleep(300)
  await shot('62-settings-rxform')
  await page.click('[data-field-toggle="duration"]')
  await page.locator('[data-section-toggle="showDiagnosis"]').dispatchEvent('click')
  await sleep(300)
  await page.click('[data-nav="rx"]')
  await page.waitForSelector('#patient-picker')
  await page.fill('#patient-picker', 'فاطمة')
  await sleep(400)
  await page.keyboard.press('Enter')
  await page.waitForSelector('#rx-patient-name')
  check((await page.locator('#rx-diagnosis').count()) === 0, 'diagnosis disappears after switching it off in Settings')
  await page.click('[data-row="0"][data-field="drugName"]')
  await page.keyboard.type('Omep', { delay: 40 })
  await sleep(500)
  await page.keyboard.press('Enter')
  await sleep(300)
  check((await page.inputValue('[data-row="0"][data-field="duration"]')) === '14 days', 'duration box appears and is filled')
  check((await page.inputValue('[data-row="0"][data-field="dose"]')) === '1 capsule · once daily · قبل الإفطار بنصف ساعة', 'dose line no longer includes the duration')
  await shot('63-custom-rx')
}
